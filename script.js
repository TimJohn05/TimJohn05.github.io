/*
  Vanilla JS for the static portfolio.
  No framework, no build step, works from file:// and GitHub Pages.
  Placeholder addresses are marked in comments so they can be replaced before publishing.
*/

(function () {
  "use strict";

  var mq = window.matchMedia("(min-width: 761px)");

  // Mobile menu toggle. Escape closes it and returns focus to the button.
  var toggle = document.querySelector(".nav-toggle");
  var nav = document.getElementById("primary-nav");

  if (toggle && nav) {
    var setMenu = function (open) {
      nav.classList.toggle("is-open", open);
      toggle.setAttribute("aria-expanded", String(open));
      toggle.setAttribute("aria-label", open ? "Close menu" : "Open menu");
    };

    toggle.addEventListener("click", function () {
      setMenu(toggle.getAttribute("aria-expanded") !== "true");
    });

    document.addEventListener("keydown", function (event) {
      if (event.key === "Escape" && toggle.getAttribute("aria-expanded") === "true") {
        setMenu(false);
        toggle.focus();
      }
    });

    // A menu opened on mobile should not linger after a resize to desktop.
    var onViewportChange = function (event) {
      if (event.matches) {
        setMenu(false);
      }
    };

    if (typeof mq.addEventListener === "function") {
      mq.addEventListener("change", onViewportChange);
    } else if (typeof mq.addListener === "function") {
      mq.addListener(onViewportChange);
    }
  }

  // Footer year.
  var year = document.getElementById("year");
  if (year) {
    year.textContent = String(new Date().getFullYear());
  }

  // Portfolio filters. The empty state is wired even though every category has work.
  var filterButtons = Array.prototype.slice.call(document.querySelectorAll(".filter-btn"));
  var galleryItems = Array.prototype.slice.call(document.querySelectorAll(".gallery__item"));
  var emptyState = document.querySelector(".grid-empty");

  filterButtons.forEach(function (button) {
    button.addEventListener("click", function () {
      var filter = button.getAttribute("data-filter");
      var shown = 0;

      filterButtons.forEach(function (other) {
        other.setAttribute("aria-pressed", String(other === button));
      });

      galleryItems.forEach(function (item) {
        var match = filter === "all" || item.getAttribute("data-category") === filter;
        item.hidden = !match;
        if (match) {
          shown += 1;
        }
      });

      if (emptyState) {
        emptyState.hidden = shown !== 0;
      }
    });
  });

  // Image error state. Placeholder hosts can be blocked by networks or ad blockers.
  var fallbackSvg =
    '<svg xmlns="http://www.w3.org/2000/svg" width="800" height="600">' +
    '<rect width="100%" height="100%" fill="#eeeeeb"/>' +
    '<text x="50%" y="50%" dominant-baseline="middle" text-anchor="middle" ' +
    'font-family="Arial, sans-serif" font-size="28" fill="#565656">Image unavailable</text>' +
    "</svg>";
  var fallbackSrc = "data:image/svg+xml;charset=utf-8," + encodeURIComponent(fallbackSvg);

  document.querySelectorAll("img[data-placeholder]").forEach(function (image) {
    image.addEventListener("error", function () {
      image.onerror = null;
      image.src = fallbackSrc;
    });
  });

  // Resume button downloads a labelled text placeholder. No server is involved.
  var resumeButton = document.getElementById("download-resume");

  if (resumeButton) {
    resumeButton.addEventListener("click", function () {
      var text = [
        "TIMOTHY JOHN LOPEZ",
        "Computer Science Student",
        "",
        "This is a placeholder resume generated by the portfolio site.",
        "Replace it with your real CV before publishing.",
        "",
        "Email: timjohnlopez@gmail.com",
        "GitHub: https://github.com/TimJohn05"
      ].join("\n");

      var url = URL.createObjectURL(new Blob([text], { type: "text/plain;charset=utf-8" }));
      var link = document.createElement("a");
      link.href = url;
      link.download = "resume-placeholder.txt";
      document.body.appendChild(link);
      link.click();
      link.remove();
      URL.revokeObjectURL(url);

      var resumeStatus = document.getElementById("resume-status");
      if (resumeStatus) {
        resumeStatus.textContent = "Downloaded. Replace this file with your real CV before publishing.";
      }
    });
  }

  // Contact form opens the visitor's email app with the message prefilled.
  // Form messages go to timjohnlopez@gmail.com. Update the address here to change it.
  var form = document.getElementById("contact-form");

  if (form) {
    form.addEventListener("submit", function (event) {
      event.preventDefault();

      var formStatus = document.getElementById("form-status");

      if (!form.checkValidity()) {
        if (formStatus) {
          formStatus.textContent = "Nothing was sent. Add your name, a valid email and a message, then try again.";
        }
        return;
      }

      var name = form.elements["name"].value.trim();
      var email = form.elements["email"].value.trim();
      var message = form.elements["message"].value.trim();
      var subject = "Portfolio enquiry from " + name;
      var body = message + "\n\nFrom: " + name + "\nEmail: " + email;

      window.location.href =
        "mailto:timjohnlopez@gmail.com?subject=" +
        encodeURIComponent(subject) +
        "&body=" +
        encodeURIComponent(body);

      if (formStatus) {
        formStatus.textContent = "Your email app should open with the message ready to send.";
      }
    });
  }
})();
